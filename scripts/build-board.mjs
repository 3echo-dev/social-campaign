#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ENTRY_MODULE, buildScriptModules, buildStyleFiles, moduleSpecifier, sha256 } from './board-modules.mjs';
import { minifyCss, minifyJs } from './minify-board.mjs';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// The job-type words the board shows (pipeline names, card labels, report kinds) come from the pipeline
// catalogue of the tree being built, so a new kind needs no board constant. A catalogue that does not line
// up with the registries throws here, so a broken board is never built.
function catalogueConfig(rootDir) {
  return createRequire(import.meta.url)(join(rootDir, 'pipeline', 'scripts', 'lib-catalogue.js')).boardConfig();
}
export function buildBoard({ config = {}, rootDir = root } = {}) {
  const src = join(rootDir, 'board', 'src');
  const html = readFileSync(join(src, 'social-campaign.html'), 'utf8');
  const css = minifyCss(readFileSync(join(src, 'board.css'), 'utf8'));
  const js = minifyJs(readFileSync(join(src, 'board.js'), 'utf8'));
  const logo = `data:image/webp;base64,${readFileSync(join(src, 'logo-reversed.webp')).toString('base64')}`;
  const safeConfig = JSON.stringify({ ...catalogueConfig(rootDir), ...config }).replace(/</g, '\\u003c');
  return '<!-- Generated by scripts/build-board.mjs. Edit board/src instead. -->\n' + html
    .replace('<!--BOARD_CSS-->', () => `<style>\n${css}\n</style>`)
    .replace('<script id="board-logo" type="text/plain">__BOARD_LOGO_DATA_URI__</script>', () => `<script id="board-logo" type="text/plain">${logo}</script>`)
    .replace('<script id="board-config" type="application/json">{}</script>', () => `<script id="board-config" type="application/json">${safeConfig}</script>`)
    .replace('<!--BOARD_JS-->', () => `<script type="module">\n${js.replace(/<\/script/gi, '<\\/script')}\n</script>`);
}
// The published form: a tiny page shell plus the board's code and styles as supporting files. The host's Artifact tool
// makes an agent read every line of a file it publishes before it may publish it, so the page stays small (the document
// skeleton, the per-workspace config, the style links and an import map) and the weight lives in several files of 20 to
// 50 KB that scripts/board-modules.mjs cuts at the `// @module` and `/* @file */` markers in board/src. The files never
// change from one workspace to the next, and a file's text changes only when its own section of the source does, so a
// refresh publishes (and the agent reads) only the files whose hash differs from the ones the bound board has.
// The logo is static, so it rides in its own small module (board-logo.js) that the entry imports first.
// Each file is linked with a ?v= of its own content hash (the import map carries it for the modules), so the page changes
// when any file does, which busts any cache, while a module's own text never holds another module's version.
export const BOARD_SHELL_FILES = Object.freeze({ js: 'board.js', css: 'board.css' });
export function buildBoardShell({ config = {}, rootDir = root } = {}) {
  const src = join(rootDir, 'board', 'src');
  const html = readFileSync(join(src, 'social-campaign.html'), 'utf8');
  const logo = `data:image/webp;base64,${readFileSync(join(src, 'logo-reversed.webp')).toString('base64')}`;
  const scripts = buildScriptModules(readFileSync(join(src, 'board.js'), 'utf8'), logo);
  const styles = buildStyleFiles(readFileSync(join(src, 'board.css'), 'utf8'));
  const files = [...styles, ...scripts].map(file => ({ path: file.path, kind: file.kind, name: file.name, text: file.text, sha256: sha256(file.text) }));
  const versionOf = file => file.sha256.slice(0, 12);
  const js = files.filter(file => file.kind === 'js').map(file => file.text).join('');
  const css = files.filter(file => file.kind === 'css').map(file => file.text).join('');
  const version = createHash('sha256').update(js, 'utf8').update('\0').update(css, 'utf8').digest('hex').slice(0, 12);
  const imports = Object.fromEntries(files.filter(file => file.kind === 'js' && file.name !== ENTRY_MODULE).map(file => [moduleSpecifier(file.name), `./${file.path}?v=${versionOf(file)}`]));
  const entry = files.find(file => file.name === ENTRY_MODULE);
  const links = files.filter(file => file.kind === 'css').map(file => `<link rel="stylesheet" href="${file.path}?v=${versionOf(file)}">`).join('\n  ');
  const safeConfig = JSON.stringify({ ...catalogueConfig(rootDir), ...config }).replace(/</g, '\\u003c');
  const page = '<!-- Generated by scripts/build-board.mjs. Edit board/src instead. -->\n' + html
    .replace('<!--BOARD_CSS-->', () => links)
    .replace('  <script id="board-logo" type="text/plain">__BOARD_LOGO_DATA_URI__</script>\n', () => '')
    .replace('<script id="board-config" type="application/json">{}</script>', () => `<script id="board-config" type="application/json">${safeConfig}</script>`)
    .replace('<!--BOARD_JS-->', () => `<script type="importmap">${JSON.stringify({ imports })}</script>\n  <script type="module" src="${entry.path}?v=${versionOf(entry)}"></script>`);
  return { html: page, js, css, version, files };
}
// What a source hash covers: the shell and every file, so a change to any file counts as a changed board.
export function boardShellHashInput(parts) {
  return `${parts.html}\0${parts.js}\0${parts.css}`;
}
export function buildBoardShellText(options) {
  return boardShellHashInput(buildBoardShell(options));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const output = join(root, 'board', 'social-campaign.html');
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, buildBoard());
  process.stdout.write(`Built ${output}\n`);
}
